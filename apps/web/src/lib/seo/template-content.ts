export function relatedRoutesFor(route: SeoRoute, types?: SeoRouteType[]) {
  const allowedTypes = types ?? ["catalog", "solution", "knowledge", "b2b"];
  return seoRoutes
    .filter((candidate) => {
      if (candidate.path === route.path) {
        return false;
      }

      return allowedTypes.includes(candidate.type);
    })
    .slice(0, 6);
}
